function buildPIControllerSubsystem(sys, inputName, outputName)
Simulink.SubSystem.deleteContents(sys);
isRateController = contains(char(inputName), 'q_error');
inputUnit = 'deg';
proportionalGain = 'pitch_Kp';
integralGain = 'pitch_Ki';
if isRateController
    inputUnit = 'deg/s';
    proportionalGain = 'pitch_rate_Kp';
    integralGain = 'pitch_rate_Ki';
end
addInport(sys, inputName, 1, [25 115 55 135], 'double', inputUnit);

pPath = [sys '/Proportional Gain'];
add_block('simulink/Math Operations/Gain', pPath, ...
    'Gain', proportionalGain, ...
    'Position', [115 70 180 110], ...
    'BackgroundColor', 'lightBlue');
iGainPath = [sys '/Integral Gain'];
add_block('simulink/Math Operations/Gain', iGainPath, ...
    'Gain', integralGain, ...
    'Position', [115 155 180 195], ...
    'BackgroundColor', 'lightBlue');
iPath = [sys '/Discrete Integrator'];
add_block('simulink/Discrete/Discrete-Time Integrator', iPath, ...
    'gainval', '1', ...
    'SampleTime', 'Sample_time', ...
    'InitialCondition', 'controller_integrator_ic', ...
    'IntegratorMethod', 'Forward Euler', ...
    'Position', [230 150 295 200], ...
    'BackgroundColor', 'lightBlue');
sumPath = [sys '/P plus I'];
add_block('simulink/Math Operations/Sum', sumPath, ...
    'Inputs', '++', ...
    'Position', [350 95 385 165], ...
    'BackgroundColor', 'yellow');
addOutport(sys, outputName, 1, [450 120 480 140], 'double', 'deg');

addNamedLine(sys, [char(inputName) '/1'], 'Proportional Gain/1', ...
    'tracking_error_deg', false);
addNamedLine(sys, [char(inputName) '/1'], 'Integral Gain/1', '', false);
addNamedLine(sys, 'Proportional Gain/1', 'P plus I/1', 'proportional_term', false);
addNamedLine(sys, 'Integral Gain/1', 'Discrete Integrator/1', '', false);
addNamedLine(sys, 'Discrete Integrator/1', 'P plus I/2', 'integral_term', false);
addNamedLine(sys, 'P plus I/1', [char(outputName) '/1'], ...
    'actuator_demand_deg', false);
addTrainingNote(sys, [40 245 455 285], ...
    'Dimensionally consistent PI gains and deterministic initial condition are controlled in FCS_Data.sldd.');
end


