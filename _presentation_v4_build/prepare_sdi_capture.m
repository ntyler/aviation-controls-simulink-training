projectRoot = fileparts(fileparts(mfilename('fullpath')));
S = load(fullfile(projectRoot,'results','AircraftFeedback_CommandTracking.mat'),'trackingTable');
T = S.trackingTable;
cmd = timeseries(T.Command_deg,T.Time_s,'Name','command'); cmd.DataInfo.Units='deg';
rsp = timeseries(T.Response_deg,T.Time_s,'Name','response'); rsp.DataInfo.Units='deg';
err = timeseries(T.Error_deg,T.Time_s,'Name','tracking_error'); err.DataInfo.Units='deg';
act = timeseries(T.ActuatorCommand,T.Time_s,'Name','actuator_command'); act.DataInfo.Units='deg';
dst = timeseries(T.Disturbance_deg_s2,T.Time_s,'Name','disturbance'); dst.DataInfo.Units='deg/s^2';
Simulink.sdi.clear;
[runID,~,sigIDs] = Simulink.sdi.createRun('AircraftFeedbackControlLoop — executed 50 Hz training result','vars',cmd,rsp,err,act,dst);
R = Simulink.sdi.getRun(runID);
R.Description = 'Imported from results/AircraftFeedback_CommandTracking.mat; generated by scripts/run_training_simulations.m';
Simulink.sdi.setSubPlotLayout(2,1);
Simulink.sdi.clearAllSubPlots;
a = Simulink.sdi.getSignal(sigIDs(1)); b = Simulink.sdi.getSignal(sigIDs(2)); c = Simulink.sdi.getSignal(sigIDs(3));
a.LineColor=[0.10 0.32 0.58]; a.LineDashed='--'; b.LineColor=[0.85 0.33 0.10]; c.LineColor=[0.49 0.18 0.56];
plotOnSubPlot(a,1,1,true); plotOnSubPlot(b,1,1,true); plotOnSubPlot(c,2,1,true);
Simulink.sdi.setMarkersOn(true);
Simulink.sdi.setGridOn('on');
Simulink.sdi.setLegendPosition('InsideRight');
Simulink.sdi.setSubplotLimits(1,1,'tRange',[14.9 15.4],'yRange',[-3.5 3.5]);
Simulink.sdi.setSubplotLimits(2,1,'tRange',[14.9 15.4],'yRange',[-0.5 6]);
Simulink.sdi.view;
disp('V4_SDI_CAPTURE_READY: authentic retained project data loaded with markers enabled.');
