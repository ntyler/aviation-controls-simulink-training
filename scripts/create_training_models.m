function startFreshModel(mdl, modelsDir)
if bdIsLoaded(mdl)
    if strcmp(get_param(mdl, 'Dirty'), 'on')
        error('TrainingModels:DirtyGeneratedModel', ...
            'Refusing to discard unsaved changes in generated model %s.', mdl);
    end
    close_system(mdl, 0);
end
existingModel = fullfile(modelsDir, [mdl '.slx']);
if isfile(existingModel)
    delete(existingModel);
end
new_system(mdl, 'Model');
set_param(mdl, ...
    'ScreenColor', 'white', ...
    'ShowPortDataTypes', 'on', ...
    'ShowLineDimensions', 'on', ...
    'ShowStorageClass', 'off');
end


