function lineHandle = addNamedLine(sys, source, destination, signalName, logSignal)
lineHandle = add_line(sys, source, destination, 'autorouting', 'on');
sourcePort = get_param(lineHandle, 'SrcPortHandle');
sourceBlock = get_param(sourcePort, 'Parent');
sourceBlockType = get_param(sourceBlock, 'BlockType');
% Bus Selector outputs inherit their element names and reject relabeling.
if ~isempty(signalName) && ~strcmp(sourceBlockType, 'BusSelector')
    set_param(lineHandle, 'Name', signalName);
end
if logSignal
    % R2023b stores signal-logging configuration on the source port rather
    % than on the line handle returned by add_line.
    set_param(sourcePort, 'DataLogging', 'on');
    if ~isempty(signalName)
        set_param(sourcePort, ...
            'DataLoggingNameMode', 'Custom', ...
            'DataLoggingName', signalName);
    end
end
end


