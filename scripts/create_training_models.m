function createAutopilotModeLogic(modelsDir)
mdl = 'AutopilotModeLogic';
startFreshModel(mdl, modelsDir);
configureDiscreteModel(mdl, 8.0);
set_param(mdl, 'Description', [ ...
    'Illustrative autopilot mode-management training logic with OFF, ' ...
    'ARMED, ENGAGED, and DEGRADED states.']);
addTrainingBanner(mdl, [ ...
    'ILLUSTRATIVE AUTOPILOT MODE LOGIC - NOT PRODUCTION AIRCRAFT LOGIC\n' ...
    'Transitions expose engagement, validity, fault, disengagement, and reset guards.']);

inputs = { ...
    'engage_request', 'sensor_valid', 'engage_success', ...
    'fault_detected', 'disengage_request', 'reset_request'};
for idx = 1:numel(inputs)
    y = 90 + (idx-1)*55;
    addInport(mdl, inputs{idx}, idx, [30 y 60 y+20], 'boolean', '1');
end

chartPath = [mdl '/Autopilot Mode Logic'];
hasStateflow = ~isempty(ver('stateflow')) && license('test', 'Stateflow');
if hasStateflow
    buildStateflowModeChart(mdl, chartPath);
    implementationText = 'Stateflow implementation: OFF / ARMED / ENGAGED / DEGRADED';
else
    add_block('simulink/Ports & Subsystems/Subsystem', chartPath, ...
        'Position', [285 85 590 405], ...
        'BackgroundColor', 'yellow');
    buildSimulinkModeFallback(chartPath);
    implementationText = [ ...
        'Stateflow license unavailable: explicit discrete Simulink fallback ' ...
        'implements OFF / ARMED / ENGAGED / DEGRADED.'];
end

addOutport(mdl, 'mode_code', 1, [720 165 750 185], 'uint8', '1');
addOutport(mdl, 'control_enabled', 2, [720 295 750 315], 'boolean', '1');
for idx = 1:numel(inputs)
    addNamedLine(mdl, sprintf('%s/1', inputs{idx}), ...
        sprintf('Autopilot Mode Logic/%d', idx), inputs{idx}, true);
end
addNamedLine(mdl, 'Autopilot Mode Logic/1', 'mode_code/1', 'mode_code', true);
addNamedLine(mdl, 'Autopilot Mode Logic/2', 'control_enabled/1', ...
    'control_enabled', true);
addTrainingNote(mdl, [185 455 635 505], implementationText);

