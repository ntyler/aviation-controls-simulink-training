function verifyDictionaryEntries(dictionaryPath, requiredEntries)
dictionary = Simulink.data.dictionary.open(char(dictionaryPath));
dictionaryCleanup = onCleanup(@()close(dictionary)); %#ok<NASGU>
section = getSection(dictionary, 'Design Data');
missing = strings(0, 1);
for idx = 1:numel(requiredEntries)
    try
        getEntry(section, char(requiredEntries(idx)));
    catch
        missing(end+1,1) = requiredEntries(idx); %#ok<AGROW>
    end
end
if ~isempty(missing)
    error('TrainingModels:MissingDictionaryEntries', ...
        'FCS_Data.sldd is missing required Design Data entries: %s', ...
        strjoin(missing, ', '));
end
end


