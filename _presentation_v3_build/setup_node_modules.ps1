$ErrorActionPreference = 'Stop'

$RuntimeModules = 'C:\Users\Tyler\.cache\codex-runtimes\codex-primary-runtime\dependencies\node\node_modules'
$LinkPath = Join-Path $PSScriptRoot 'node_modules'

if (Test-Path -LiteralPath $LinkPath) {
    $item = Get-Item -LiteralPath $LinkPath -Force
    if ($item.LinkType -ne 'Junction' -or $item.Target -ne $RuntimeModules) {
        throw "Existing node_modules is not the required runtime junction: $LinkPath"
    }
} else {
    New-Item -ItemType Junction -Path $LinkPath -Target $RuntimeModules | Out-Null
}
