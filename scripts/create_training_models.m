function createdFiles = create_training_models(projectRoot)
%CREATE_TRAINING_MODELS Build the aviation-controls Simulink training set.
%
%   createdFiles = CREATE_TRAINING_MODELS() locates the project from this
%   file, links every model to data/FCS_Data.sldd, creates the models in
%   models/, updates each diagram, and returns the absolute model paths.
%
%   createdFiles = CREATE_TRAINING_MODELS(projectRoot) uses the supplied
%   project root. The function is intentionally rerunnable: generated model
%   files are replaced, while files outside models/ are not modified.
%
%   Run initialize_training_data before this function. All numeric design
%   constants are illustrative training values stored in FCS_Data.sldd;
%   none represent production aircraft data.

arguments
    projectRoot (1,1) string = ""
end

if strlength(projectRoot) == 0
    projectRoot = string(fileparts(fileparts(mfilename('fullpath'))));
end
[status, attributes] = fileattrib(char(projectRoot));
if ~status
    error('TrainingModels:InvalidProjectRoot', ...
        'Could not resolve project root: %s', projectRoot);
end
projectRoot = string(attributes.Name);
modelsDir = fullfile(projectRoot, "models");
dataDir = fullfile(projectRoot, "data");
dictionaryPath = fullfile(dataDir, "FCS_Data.sldd");

if ~isfolder(modelsDir)
    error('TrainingModels:MissingModelsDirectory', ...
        'Expected models directory does not exist: %s', modelsDir);
end
if ~isfile(dictionaryPath)
    error('TrainingModels:MissingDictionary', ...
        ['FCS_Data.sldd was not found at %s. Run ' ...
         'initialize_training_data.m before create_training_models.m.'], ...
        dictionaryPath);
end

requiredEntries = [ ...
    "Sample_time", "q_limit_normal", "q_fallback_command", ...
    "pitch_Kp", "pitch_Ki", "pitch_rate_Kp", "pitch_rate_Ki", ...
    "controller_integrator_ic", ...
    "actuator_limit_deg", "actuator_filter_alpha", ...
    "aircraft_control_effectiveness", "aircraft_pitch_damping", ...
    "initial_q_rate", "initial_pitch_angle", ...
    "sensor_filter_alpha", "normal_mode_code", "FlightControlBus"];
verifyDictionaryEntries(dictionaryPath, requiredEntries);

pathWasAdded = false;
if ~contains(path, char(dataDir))
    addpath(char(dataDir));
    pathWasAdded = true;
end
pathCleanup = onCleanup(@()restoreTemporaryPaths( ...
    char(dataDir), pathWasAdded)); %#ok<NASGU>

load_system('simulink');

modelNames = [ ...
    "PitchRateLimiter", ...
    "AircraftFeedbackControlLoop", ...
    "AutopilotModeLogic", ...
    "SensorProcessingRef", ...
    "PitchControllerRef", ...
    "ActuatorCommandRef", ...
    "ReferencedFlightControlArchitecture", ...
    "PitchRateLimiter_Harness"];

try
    createPitchRateLimiter(modelsDir);
    createAircraftFeedbackControlLoop(modelsDir);
    createAutopilotModeLogic(modelsDir);

    % Referenced children must be saved and updated before the parent model
    % reference blocks are instantiated so their port interfaces are known.
    createSensorProcessingReference(modelsDir);
    createPitchControllerReference(modelsDir);
    createActuatorCommandReference(modelsDir);
    createReferencedArchitecture(modelsDir);
    createPitchRateLimiterHarness(modelsDir);

    for idx = 1:numel(modelNames)
        mdl = char(modelNames(idx));
        load_system(mdl);
        set_param(mdl, 'SimulationCommand', 'update');
        save_system(mdl);
    end
catch ME
    generated = modelNames(arrayfun(@(n)bdIsLoaded(char(n)), modelNames));
    for idx = 1:numel(generated)
        try
            close_system(char(generated(idx)), 0);
        catch
            % Preserve the original failure; cleanup errors are secondary.
        end
    end
    wrapper = MException('TrainingModels:BuildFailed', ...
        'Simulink training-model generation failed: %s', ME.message);
    throwAsCaller(addCause(wrapper, ME));
end

createdFiles = strings(numel(modelNames), 1);
for idx = 1:numel(modelNames)
    createdFiles(idx) = fullfile(modelsDir, modelNames(idx) + ".slx");
end

fprintf('Created and updated %d training models in:\n  %s\n', ...
    numel(createdFiles), modelsDir);
end


function createPitchRateLimiter(modelsDir)
mdl = 'PitchRateLimiter';
startFreshModel(mdl, modelsDir);
configureDiscreteModel(mdl, 4.0);
set_param(mdl, 'Description', [ ...
    'Illustrative 50 Hz pitch-rate command magnitude limiter. ' ...
    'Valid normal-mode inputs are clamped inclusively to plus/minus ' ...
    'q_limit_normal; invalid or non-normal inputs use q_fallback_command.']);

addTrainingBanner(mdl, [ ...
    'ILLUSTRATIVE TRAINING MODEL - NOT PRODUCTION AIRCRAFT DATA\n' ...
    'Pitch-rate MAGNITUDE limiter at 50 Hz. This is not a slew-rate limiter.']);

addInport(mdl, 'q_cmd_in', 1, [35 130 65 150], 'double', 'deg/s');
addInport(mdl, 'normal_mode', 2, [35 205 65 225], 'boolean', '1');
addInport(mdl, 'input_valid', 3, [35 270 65 290], 'boolean', '1');

logicPath = [mdl '/Pitch Rate Limiter Logic'];
add_block('simulink/Ports & Subsystems/Subsystem', logicPath, ...
    'Position', [190 105 440 315], ...
    'BackgroundColor', 'lightBlue', ...
    'ForegroundColor', 'blue');
set_param(logicPath, 'Description', [ ...
    'Inclusive magnitude clamp plus explicit validity/mode fallback. ' ...
    'limiter_active is true only while a valid command exceeds a limit.']);
buildPitchLimiterSubsystem(logicPath);

addOutport(mdl, 'q_cmd_out', 1, [575 145 605 165], 'double', 'deg/s');
addOutport(mdl, 'limiter_active', 2, [575 245 605 265], 'boolean', '1');

addNamedLine(mdl, 'q_cmd_in/1', 'Pitch Rate Limiter Logic/1', ...
    'q_cmd_in_deg_s', true);
addNamedLine(mdl, 'normal_mode/1', 'Pitch Rate Limiter Logic/2', ...
    'normal_mode', true);
addNamedLine(mdl, 'input_valid/1', 'Pitch Rate Limiter Logic/3', ...
    'input_valid', true);
addNamedLine(mdl, 'Pitch Rate Limiter Logic/1', 'q_cmd_out/1', ...
    'q_cmd_out_deg_s', true);
addNamedLine(mdl, 'Pitch Rate Limiter Logic/2', 'limiter_active/1', ...
    'limiter_active', true);

saveGeneratedModel(mdl, modelsDir);
end


